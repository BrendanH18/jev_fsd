globalThis.document = { querySelector: () => null };
import assert from 'node:assert/strict';
import fs from 'node:fs';
const { MapData } = await import('../static/js/map/mapdata.js');
const { busLaneActive, legalBusLane, routeBusLane, auditBusLanes } = await import('../static/js/sim/bus-lanes.js');
const { CHALLENGES, challengeScenario } = await import('../static/js/lab/challenges.js');
const { setupChallenge, evaluateChallenge } = await import('../static/js/lab/evaluation.js');
const { busTravelLane } = await import('../static/js/sim/bus.js');
const { NpcPath } = await import('../static/js/sim/npc.js');
const { toJevState, situationClauses } = await import('../static/js/brain/state.js');
const { buildSnapshot } = await import('../static/js/brain/sensors.js');
const { failures } = await import('../static/js/bench/metrics.js');
const key='7165f1c807a8';
const pack=JSON.parse(fs.readFileSync(`data/maps/${key}.v6.pack.json`));
for(const layer of ['transit','crossings','zones','rail','calming','scrambles','buslanes','restrictions']) { const file=[2,1].map(v=>`data/maps/${key}.${layer}.v${v}.json`).find(f=>fs.existsSync(f)); if(file) pack[layer]=JSON.parse(fs.readFileSync(file)); }
const map=new MapData(pack), c=CHALLENGES.find(c=>c.id==='bus-lanes');
assert.equal(map.buslanes.length>0,true);
const timed={hours:[{days:[0,1,2,3,4],start:420,end:540}],allowed:['bus']};
assert.equal(busLaneActive(timed,{hour:8,weekday:0}),true);
assert.equal(busLaneActive(timed,{hour:9,weekday:0}),false);
assert.equal(busLaneActive(timed,{hour:8,weekday:6}),false);
assert.equal(busLaneActive(timed,null),false);
const e=map.edges.get(map.buslanes[0].edge), r=map.buslanes[0];
assert.equal(legalBusLane(map,e.id,r.lane,{hour:8},'straight',20),false);
assert.equal(legalBusLane(map,e.id,r.lane,{hour:8},'right',50),true);
assert.equal(legalBusLane(map,e.id,r.lane,{hour:8},'right',51),false);
assert.equal(legalBusLane(map,e.id,r.lane,{hour:8},'straight',100,false,'bus'),true);
assert.equal(legalBusLane(map,e.id,r.lane,{hour:8},'straight',100,true),true);
const scenario=challengeScenario(map,c);
assert.equal(scenario.route.turns.some(t=>t.dir==='right'),true);
const ctx=setupChallenge(map,c);
const snap = buildSnapshot(ctx.world);
assert.equal(snap.bus_lane.in_effect,true);
assert.equal(toJevState(snap,[],{}).bus_lane.in_effect,true);
assert.equal(situationClauses(snap).some(t=>t.includes('final 50 m')),true);
const path = new NpcPath(map,()=>.5);
path.busLanePolicy = {clock:ctx.world.clock};
const predecessor = (map.inn.get(map.edges.get(scenario.start.edge).from)||[])[0];
if(predecessor) assert.equal(path.laneInto(predecessor,busLaneIndex(),scenario.start.edge) < busLaneIndex(),true);
path.busLanePolicy.bus = true;
assert.equal(busTravelLane(map,map.edges.get(scenario.start.edge),ctx.world.clock),busLaneIndex());
if(predecessor) assert.equal(path.laneInto(predecessor,0,scenario.start.edge),busLaneIndex());
function busLaneIndex() { return map.edges.get(scenario.start.edge).lanes - 1; }
const buslane = map.lane(scenario.start.edge, map.edges.get(scenario.start.edge).lanes - 1);
ctx.world.placeOnLane(buslane, 15); ctx.world.ego.v = 5;
auditBusLanes(ctx.world, 1);
assert.equal(ctx.world.busLanesSeen, true);
assert.equal(ctx.world.violations.bus_lane_driving, 5);
ctx.world.placeOnLane(buslane, buslane.length - 30); ctx.world.ego.v = 5;
auditBusLanes(ctx.world, 1);
assert.equal(ctx.world.violations.bus_lane_driving, 5);
ctx.world.busLanes=false; delete ctx.world.route.busLanePolicy;
assert.equal('bus_lane' in buildSnapshot(ctx.world),false);
assert.equal(failures({bus_lane_driving:2}).includes('drove in a reserved bus lane'),true);
for(const brain of ['rules','cautious']) {
 const result=await evaluateChallenge(map,c,{brain,limit:120});
 assert.equal(result.pass,true);
 assert.equal(result.bus_lane_driving,0);
 assert.equal(result.lane_changes > 0,true);
 console.log(brain,JSON.stringify({pass:result.pass,arrived:result.arrived,time:result.duration_s,bus:result.bus_lane_driving,failures:result.failures}));
}
console.log('bus lane policy checks passed');
process.exit(0);
